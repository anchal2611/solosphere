export const mergeBlogPosts = (savedPosts = []) => {
  const mergedPosts = new Map(BLOG_POSTS.map(post => [String(post.id), post]));

  (Array.isArray(savedPosts) ? savedPosts : []).forEach(post => {
    const key = String(post.id ?? post.title);
    mergedPosts.set(key, { ...mergedPosts.get(key), ...post });
  });

  return Array.from(mergedPosts.values());
};
